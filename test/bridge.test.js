import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';

test('browser fallback and atomic MCP commands use real store/history', async () => {
  const vite = await createServer({ server: { middlewareMode: true, hmr: false }, appType: 'custom', optimizeDeps: { noDiscovery: true, include: [] } });
  const oldDocument = globalThis.document;
  try {
    const { useStoryStore: store } = await vite.ssrLoadModule('/src/store.js');
    const { executeStoryCommand: execute, layoutNodes } = await vite.ssrLoadModule('/src/services/storyCommands.js');
    const { getStorageService, BrowserStorageService, TauriStorageService } = await vite.ssrLoadModule('/src/services/storage/index.js');
    assert.ok(getStorageService('tauri') instanceof BrowserStorageService);
    const adapter = new TauriStorageService();
    adapter.local.saveProject = async () => ({ success: true, fallback: true });
    adapter.local.open = async () => ({ fallback: true });
    adapter.local.exportJson = async () => ({ fallback: true });
    adapter.local.exportStandaloneHtml = async () => ({ fallback: true });
    adapter.local.listProjects = async () => [];
    assert.equal((await adapter.saveProject({})).fallback, true);
    assert.equal((await adapter.saveAs({})).fallback, true);
    assert.equal((await adapter.open()).fallback, true);
    assert.equal((await adapter.exportJson({})).fallback, true);
    assert.equal((await adapter.exportStandaloneHtml({})).fallback, true);
    assert.deepEqual(await adapter.listProjects(), []);
    globalThis.document = { body: { className: '' } };
    await store.getState().resetProject('blank', false);
    store.setState({ nodes: [], edges: [], characters: [], variables: [] });
    store.temporal.getState().clear();
    const call = (tool, args = {}) => execute(store, tool, args);
    call('manage_character', { name: 'Ada', faction: 'Explorers', color: '#00aaff' });
    const characterId = store.getState().characters[0].id;
    call('manage_character', { name: 'Ada', faction: 'Explorers', color: '#ffffff' });
    assert.equal(store.getState().characters.length, 1);
    assert.equal(store.getState().characters[0].id, characterId);
    call('manage_variable', { name: 'key', type: 'boolean', initialValue: false });
    const before = JSON.stringify(store.getState().getSerializableData());
    assert.throws(() => call('manage_variable', { name: 'key', type: 'number', initialValue: 3 }), /Cannot change type/);
    assert.equal(JSON.stringify(store.getState().getSerializableData()), before);
    const first = call('create_scene_node', { title: 'Start', nodeType: 'start', dialogue: [{ characterName: 'Ada', text: 'Hello' }] });
    const second = call('create_scene_node', { title: 'End', nodeType: 'ending', parentSceneId: first.sceneId });
    const historyLength = store.temporal.getState().pastStates.length;
    const branch = call('create_choice_branch', { fromSceneId: first.sceneId, toSceneId: second.sceneId, choiceText: 'Open', conditions: [{ varName: 'key', operator: '==', value: true }] });
    assert.equal(store.temporal.getState().pastStates.length, historyLength + 1);
    assert.equal(store.getState().edges[0].sourceHandle, branch.choiceId);
    assert.equal(store.getState().nodes[0].data.choices[0].id, branch.choiceId);
    store.temporal.getState().undo();
    assert.equal(store.getState().edges.length, 0);
    assert.equal(store.getState().nodes[0].data.choices.length, 0);
    store.temporal.getState().redo();
    const snapshot = JSON.stringify(store.getState().getSerializableData());
    assert.throws(() => call('create_choice_branch', { fromSceneId: first.sceneId, toSceneId: second.sceneId, choiceText: 'Bad', conditions: [{ varName: 'missing', operator: '==', value: true }] }), /Unknown variable/);
    assert.throws(() => call('create_choice_branch', { fromSceneId: second.sceneId, toSceneId: first.sceneId, choiceText: 'Bad' }), /ending/);
    assert.equal(JSON.stringify(store.getState().getSerializableData()), snapshot);
    const overview = call('get_story_overview');
    assert.equal(overview.scenes[0].dialogue[0].characterName, 'Ada');
    assert.equal(overview.characters[0].faction, 'Explorers');
    assert.equal(overview.branches.length, 1);
    call('autolayout_canvas');
    const node = (id, choices = []) => ({ id, position: { x: 0, y: 0 }, data: { choices } });
    const laidOut = layoutNodes([node('a', Array.from({ length: 30 }, (_, i) => ({ id: `c${i}` }))), node('b'), node('c')], [{ source: 'a', target: 'b' }, { source: 'b', target: 'a' }]);
    assert.ok(laidOut.every(item => Number.isFinite(item.position.x) && Number.isFinite(item.position.y)));
    assert.ok(laidOut[2].position.y - laidOut[0].position.y >= 1010);
    store.getState().clearToast();
  } finally { await vite.close(); globalThis.document = oldDocument; }
});